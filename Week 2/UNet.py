class Dataset(data.Dataset):
  def __init__(self, path, transform, id_):
    super().__init__()
    self.path = path
    self.transform = transform
    self.id_ = id_

  def __len__(self):
    return len(self.id_)

  def __getitem__(self, idx):
    img_folder = os.path.join(self.path, self.id_[idx], "images")
    img_files = glob.glob(os.path.join(img_folder, "*"))
    if not img_files:
        raise FileNotFoundError(f"No image found in {img_folder}")

    image = Image.open(img_files[0]).convert('RGB')
    image = self.transform(image)
    image = F.resize(image, (256, 256))

    path_mask = os.path.join(self.path, self.id_[idx], "masks")
    mask_files = glob.glob(os.path.join(path_mask, "*.png"))
    if not mask_files:
        raise FileNotFoundError(f"No masks found in {path_mask}")

    first_mask = cv2.imread(mask_files[0], cv2.IMREAD_GRAYSCALE)
    combined_mask = np.zeros_like(first_mask, dtype=np.uint8)

    for mask_file in mask_files:
      mask = cv2.imread(mask_file, cv2.IMREAD_GRAYSCALE)
      combined_mask = np.maximum(combined_mask, mask)

    combined_mask_tensor = torch.from_numpy(combined_mask).long()
    combined_mask_tensor[combined_mask_tensor == 255] = 1
    combined_mask_tensor = F.resize(combined_mask_tensor.unsqueeze(0), (256, 256)).squeeze(0)
    return image, combined_mask_tensor

